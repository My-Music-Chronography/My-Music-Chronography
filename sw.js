// My Music Chronography service worker: keeps the app itself offline, and every cover it has shown.
// When you upload a new index.html, change VERSION so installed copies pick it up.
const VERSION = 'chronography-v21';
const SHELL = ['./', './index.html', './manifest.webmanifest', './icon-192.png', './icon-512.png', './apple-touch-icon.png'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== VERSION && k !== 'chronography-covers').map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // MusicBrainz lookups: always live
  if (url.hostname === 'musicbrainz.org') return;
  // covers: from the cache when we have them, else fetched and kept
  if (url.hostname.endsWith('coverartarchive.org') || url.hostname.endsWith('archive.org')) {
    e.respondWith(caches.open('chronography-covers').then(async c => {
      const hit = await c.match(req);
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok || res.type === 'opaque') c.put(req, res.clone());
      return res;
    }));
    return;
  }
  // the app: network first so updates land, the cached copy when offline
  if (url.origin === location.origin) {
    e.respondWith(fetch(req).then(res => {
      if (res.ok) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match(req).then(r => r || caches.match('./index.html'))));
  }
});
